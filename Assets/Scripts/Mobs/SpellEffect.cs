using UnityEngine;

public class SpellEffect : MonoBehaviour
{
    public int damage = 15;
    public float lifetime = 1.5f;     // ????? ??????? ?????? ????????
    public float damageDelay = 0.4f;  // ????? ??????? ???? (????? ???????? ???????)
    public float damageRadius = 0.7f;
    public LayerMask playerLayer;

    bool damageDone = false;
    float timer;

    void Update()
    {
        timer += Time.deltaTime;

        // ? ?????? damageDelay — ??????? ???? ??? ??? ????? ? ???? ???????
        if (!damageDone && timer >= damageDelay)
        {
            damageDone = true;
            DealDamage();
        }

        // ?????????? ????? lifetime
        if (timer >= lifetime)
            Destroy(gameObject);
    }

    void DealDamage()
    {
        // ???? ?????? ? ???? ???????
        Collider2D[] hits = Physics2D.OverlapCircleAll(transform.position, damageRadius, playerLayer);

        foreach (var c in hits)
        {
            var hp = c.GetComponent<Health>();
            if (hp != null && !hp.IsDead)
            {
                hp.TakeDamage(damage);

                // Knockback ????? — ???????? ????????????
                var rb = c.GetComponent<Rigidbody2D>();
                if (rb != null)
                    rb.AddForce(Vector2.up * 4f, ForceMode2D.Impulse);
            }
        }
    }

    // ????? ?????? ???? ????? ? ?????????
    void OnDrawGizmosSelected()
    {
        Gizmos.color = new Color(0.7f, 0.3f, 1f);
        Gizmos.DrawWireSphere(transform.position, damageRadius);
    }
}
